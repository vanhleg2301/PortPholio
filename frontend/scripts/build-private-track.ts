// Checks a private study track and writes the SQL that uploads it (owner-only table, see
// supabase/migrations/012_private_tracks.sql). The track's content is kept outside this public
// repository; only this tool lives here.
//
//   npx tsx scripts/build-private-track.ts <track.ts> <out.sql>
//
// <track.ts> default-exports a PrivateTrackSource. Paste <out.sql> into the Supabase SQL Editor;
// running it again replaces the track (progress is kept: task ids depend on lesson ids).
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { trackSchema } from '../src/lib/privateTrackSchema'
import { GLOSSARY } from '../src/data/lessons/glossary'

const [input, output] = process.argv.slice(2)
if (!input || !output) {
  console.error('Usage: npx tsx scripts/build-private-track.ts <track.ts> <out.sql>')
  process.exit(1)
}

const mod = (await import(pathToFileURL(resolve(input)).href)) as { default: unknown }
const parsed = trackSchema.safeParse(mod.default)
if (!parsed.success) {
  console.error(parsed.error.issues.map((i) => `- ${i.path.join('.')}: ${i.message}`).join('\n'))
  process.exit(1)
}
const track = parsed.data
const problems: string[] = []
const fail = (msg: string) => problems.push(msg)

const lessonIds = new Set<string>()
for (const lesson of track.lessons) {
  if (lessonIds.has(lesson.id)) fail(`duplicate lesson id ${lesson.id}`)
  lessonIds.add(lesson.id)
}
const planned = track.modules.flatMap((m) => m.days.flatMap((d) => d.lessons))
for (const id of planned) if (!lessonIds.has(id)) fail(`a day lists unknown lesson ${id}`)
for (const id of lessonIds) if (!planned.includes(id)) fail(`lesson ${id} is in no day`)

// Section names a primer may point at: `## headings` of the lesson.
const headings = new Map(
  track.lessons.map((l) => [
    l.id,
    new Set(l.blocks.flatMap((b) => (b.type === 'text' ? b.md.split('\n').filter((x) => x.startsWith('## ')).map((x) => x.slice(3).replace(/[*_`]/g, '').trim()) : []))),
  ])
)
const TERM = /\[\[([A-Za-z][^\]|\n]*)(?:\|[^\]\n]+)?\]\]/g
const words = new Set([...Object.keys(GLOSSARY), ...Object.keys(track.glossary)])
function checkTerms(where: string, md: string) {
  for (const m of md.replace(/```[\s\S]*?```|`[^`\n]*`/g, '').matchAll(TERM)) if (!words.has(m[1].trim().toLowerCase())) fail(`${where}: unknown word "${m[1]}"`)
}
for (const lesson of track.lessons) for (const b of lesson.blocks) if (b.type === 'text' || b.type === 'callout') checkTerms(lesson.id, b.md)

for (const [lessonId, test] of Object.entries(track.tests)) {
  if (!lessonIds.has(lessonId)) fail(`test for unknown lesson ${lessonId}`)
  const ids = new Set<string>()
  const concepts = new Map<string, number>()
  for (const q of [...test.choice, ...test.explain]) {
    if (ids.has(q.id)) fail(`${lessonId}: duplicate question id ${q.id}`)
    ids.add(q.id)
    if (q.primer?.section && !headings.get(lessonId)?.has(q.primer.section)) fail(`${lessonId}/${q.id}: primer section "${q.primer.section}" is not a heading`)
    if (q.primer) checkTerms(`${lessonId}/${q.id}`, q.primer.read)
  }
  for (const q of test.choice) {
    concepts.set(q.concept ?? q.id, (concepts.get(q.concept ?? q.id) ?? 0) + 1)
    if (new Set(q.options).size !== q.options.length) fail(`${lessonId}/${q.id}: duplicate options`)
    checkTerms(`${lessonId}/${q.id}`, `${q.question}\n${q.explain}`)
  }
  for (const [concept, n] of concepts) if (n < 2) fail(`${lessonId}: concept ${concept} has only ${n} question`)
  for (const q of test.explain) checkTerms(`${lessonId}/${q.id}`, `${q.question}\n${q.answer}`)
}

if (problems.length > 0) {
  console.error(`${problems.length} problem(s):\n- ${problems.join('\n- ')}`)
  process.exit(1)
}

const json = JSON.stringify(mod.default)
let tag = 'track'
while (json.includes(`$${tag}$`)) tag += '_'
const sql = `-- Generated by scripts/build-private-track.ts — upload or replace the private track "${track.id}".
INSERT INTO roadmap_private_tracks (id, data, updated_at)
VALUES ('${track.id}', $${tag}$${json}$${tag}$::jsonb, NOW())
ON CONFLICT (id) DO UPDATE SET data = EXCLUDED.data, updated_at = NOW();
`
writeFileSync(output, sql)
const days = track.modules.reduce((n, m) => n + m.days.length, 0)
console.log(`OK: ${track.id} — ${track.modules.length} modules, ${days} days, ${track.lessons.length} lessons → ${output}`)
